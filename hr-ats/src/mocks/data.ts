const stageDefsByJob: Record<string, { name: string; type: PipelineStage["stage_type"] }[]> = {
  default: [
    { name: "New Applicant", type: "active" },
    { name: "AI Screening", type: "active" },
    { name: "HR Screening", type: "active" },
    { name: "Technical Interview", type: "active" },
    { name: "Offer", type: "active" },
    { name: "Hired", type: "hired" },
    { name: "Rejected", type: "rejected" },
  ],
};

export function buildStagesForJob(jobId: string): PipelineStage[] {
  const defs = stageDefsByJob.default;
  return defs.map((d, i) => ({
    id: `${jobId}-${i + 1}`,
    job_id: jobId,
    name: d.name,
    order: i + 1,
    stage_type: d.type,
    candidate_count: Math.max(0, 8 - i * 2 + (i === 5 ? 3 : 0)),
  }));
}

